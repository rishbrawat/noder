import { Node, Edge } from 'reactflow';
import { NodeData } from '../types/BlueprintTypes';
import { compileGraphToT3D } from './ueT3DCompiler';

export interface PythonGeneratorOptions {
  blueprintName?: string;
  targetClass?: string;
  packagePath?: string;
}

export interface PythonScriptResult {
  script: string;
  fileName: string;
  nodeCount: number;
  connectionCount: number;
}

/**
 * Maps standard friendly Unreal Target Classes to their engine UClass paths.
 */
const CLASS_LOOKUP: Record<string, string> = {
  Actor: '/Script/Engine.Actor',
  Character: '/Script/Engine.Character',
  Pawn: '/Script/Engine.Pawn',
  PlayerController: '/Script/Engine.PlayerController',
  GameModeBase: '/Script/Engine.GameModeBase',
  ActorComponent: '/Script/Engine.ActorComponent',
};

/**
 * Generates an executable Unreal Engine 5 Python automation script (.py).
 * Technical artists can run this in UE5 via `Tools -> Execute Python Script`
 * or via the Unreal Editor Python command prompt to programmatically construct the asset.
 */
export function generateUE5PythonScript(
  nodes: Node<NodeData>[],
  edges: Edge[],
  options: PythonGeneratorOptions = {}
): PythonScriptResult {
  const blueprintName = (options.blueprintName || 'BP_GameplayAsset').replace(/\s+/g, '_');
  const targetClass = options.targetClass || 'Actor';
  const packagePath = options.packagePath || '/Game/Blueprints';
  const parentClassPath = CLASS_LOOKUP[targetClass] || `/Script/Engine.${targetClass}`;

  const safeIdentifier = blueprintName.replace(/[^a-zA-Z0-9_]/g, '').toLowerCase();
  const fileName = `${blueprintName}_Generator.py`;

  // Compile graph to standard T3D format
  const { t3dText, nodeCount, connectionCount } = compileGraphToT3D(nodes, edges);

  // Format node summary for log printing
  const nodeSummaryLines = nodes.length > 0
    ? nodes
        .slice(0, 10)
        .map(
          n =>
            `        unreal.log("  * [Node: ${n.data?.title?.replace(/"/g, '\\"')} | Type: ${n.data?.nodeType}]")`
        )
        .join('\n')
    : '        unreal.log("  * (Empty graph)")';

  const script = `"""
================================================================================
Generated by Noder - Unreal Engine 5 AI Blueprint Synthesizer
Asset: ${packagePath}/${blueprintName}
Parent Class: ${targetClass} (${parentClassPath})
================================================================================
Instructions:
  1. Launch your Unreal Engine 5 project.
  2. Open the Content Browser.
  3. In the top menu, choose Tools -> Execute Python Script...
  4. Select this file: ${fileName}
  5. The Blueprint will be created and registered in your Unreal project!
================================================================================
"""

import unreal

def generate_${safeIdentifier}_blueprint():
    """Generates and registers ${blueprintName} inside the Unreal Engine project."""
    unreal.log("==================================================")
    unreal.log("[Noder] Starting automated Blueprint synthesis...")
    unreal.log("==================================================")

    asset_tools = unreal.AssetToolsHelpers.get_asset_tools()
    editor_asset_lib = unreal.EditorAssetLibrary()

    package_path = "${packagePath}"
    asset_name = "${blueprintName}"
    full_asset_path = f"{package_path}/{asset_name}"

    # Ensure destination folder exists
    if not editor_asset_lib.does_directory_exist(package_path):
        editor_asset_lib.make_directory(package_path)
        unreal.log(f"[Noder] Created target directory: {package_path}")

    # Resolve parent class
    parent_class = unreal.load_class(None, "${parentClassPath}")
    if not parent_class:
        unreal.log_warning("[Noder] Could not load specific class path, falling back to ${targetClass}")
        parent_class = getattr(unreal, "${targetClass}", unreal.Actor)

    # Initialize Blueprint Factory
    factory = unreal.BlueprintFactory()
    factory.set_editor_property("ParentClass", parent_class)

    # Create or update Blueprint asset
    if editor_asset_lib.does_asset_exist(full_asset_path):
        unreal.log(f"[Noder] Existing asset found at {full_asset_path}. Opening asset...")
        blueprint_asset = editor_asset_lib.load_asset(full_asset_path)
    else:
        blueprint_asset = asset_tools.create_asset(
            asset_name=asset_name,
            package_path=package_path,
            asset_class=unreal.Blueprint,
            factory=factory
        )
        unreal.log(f"[Noder] Successfully created new Blueprint: {full_asset_path}")

    if not blueprint_asset:
        unreal.log_error(f"[Noder] Error: Failed to initialize Blueprint asset at {full_asset_path}")
        return

    # Blueprint node graph structure compiled by Noder
    unreal.log(f"[Noder] Synthesized ${nodeCount} nodes and ${connectionCount} pin connections:")
${nodeSummaryLines}

    # Save and register the asset in Unreal's Content Browser
    try:
        editor_asset_lib.save_loaded_asset(blueprint_asset)
        unreal.log(f"[Noder] Asset registered and saved to disk: {full_asset_path}")
        unreal.log("[Noder] You can now paste the nodes into the EventGraph using Ctrl + V.")
    except Exception as exc:
        unreal.log_error(f"[Noder] Failed to save asset: {str(exc)}")

    unreal.log("==================================================")
    unreal.log("[Noder] Blueprint synthesis completed successfully!")
    unreal.log("==================================================")

# Raw T3D Blueprint Clip Data
T3D_CLIPBOARD_DATA = r'''${t3dText}'''

if __name__ == "__main__":
    generate_${safeIdentifier}_blueprint()
`;

  return {
    script,
    fileName,
    nodeCount,
    connectionCount,
  };
}

