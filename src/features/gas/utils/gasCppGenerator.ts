import { 
  AttributeDefinition, 
  GameplayAbilityDefinition, 
  GameplayEffectDefinition 
} from '../types/gasTypes';

export interface GasCppOutput {
  headerFile: string;
  sourceFile: string;
  className: string;
}

/**
 * Formats a number as a C++ float literal (e.g. 100.0f or 1.5f).
 */
export function formatCppFloat(value: number): string {
  return Number.isInteger(value) ? `${value}.0f` : `${value}f`;
}

/**
 * Generates Unreal Engine 5 production-ready C++ AttributeSet scaffolding (.h and .cpp)
 * with ATTRIBUTE_ACCESSORS, PreAttributeChange, and PostGameplayEffectExecute clamping.
 */
export function generateAttributeSetCpp(
  className: string,
  attributes: AttributeDefinition[]
): GasCppOutput {
  const cleanClassName = className.startsWith('U') ? className : `U${className}`;
  const rawName = cleanClassName.substring(1);

  // Header (.h)
  const headerLines: string[] = [
    `// Generated by Noder GAS Studio — Unreal Engine 5 C++ Scaffolding`,
    `#pragma once`,
    ``,
    `#include "CoreMinimal.h"`,
    `#include "AttributeSet.h"`,
    `#include "AbilitySystemComponent.h"`,
    `#include "${rawName}.generated.h"`,
    ``,
    `// Macro defining standard getter, setter, and init helpers for GAS attributes`,
    `#define ATTRIBUTE_ACCESSORS(ClassName, PropertyName) \\`,
    `\tGAMEPLAYATTRIBUTE_PROPERTY_GETTER(ClassName, PropertyName) \\`,
    `\tGAMEPLAYATTRIBUTE_VALUE_GETTER(PropertyName) \\`,
    `\tGAMEPLAYATTRIBUTE_VALUE_SETTER(PropertyName) \\`,
    `\tGAMEPLAYATTRIBUTE_VALUE_INITTER(PropertyName)`,
    ``,
    `UCLASS()`,
    `class YOURGAME_API ${cleanClassName} : public UAttributeSet`,
    `{`,
    `\tGENERATED_BODY()`,
    ``,
    `public:`,
    `\t${cleanClassName}();`,
    ``,
    `\tvirtual void PreAttributeChange(const FGameplayAttribute& Attribute, float& NewValue) override;`,
    `\tvirtual void PostGameplayEffectExecute(const FGameplayEffectModCallbackData& Data) override;`,
    `\tvirtual void GetLifetimeReplicatedProps(TArray<FLifetimeProperty>& OutLifetimeProps) const override;`,
    ``,
  ];

  attributes.forEach((attr) => {
    headerLines.push(`\t// ${attr.description}`);
    headerLines.push(`\tUPROPERTY(BlueprintReadOnly, Category = "${attr.category}", ReplicatedUsing = OnRep_${attr.name})`);
    headerLines.push(`\tFGameplayAttributeData ${attr.name};`);
    headerLines.push(`\tATTRIBUTE_ACCESSORS(${cleanClassName}, ${attr.name});`);
    headerLines.push(``);
    headerLines.push(`\tUFUNCTION()`);
    headerLines.push(`\tvirtual void OnRep_${attr.name}(const FGameplayAttributeData& Old${attr.name});`);
    headerLines.push(``);
  });

  headerLines.push(`};`);

  // Source (.cpp)
  const sourceLines: string[] = [
    `// Generated by Noder GAS Studio — Unreal Engine 5 C++ Scaffolding`,
    `#include "${rawName}.h"`,
    `#include "Net/UnrealNetwork.h"`,
    `#include "GameplayEffectExtension.h"`,
    ``,
    `${cleanClassName}::${cleanClassName}()`,
    `{`,
  ];

  attributes.forEach((attr) => {
    sourceLines.push(`\tInit${attr.name}(${formatCppFloat(attr.defaultValue)});`);
  });

  sourceLines.push(`}`);
  sourceLines.push(``);

  // PreAttributeChange
  sourceLines.push(`void ${cleanClassName}::PreAttributeChange(const FGameplayAttribute& Attribute, float& NewValue)`);
  sourceLines.push(`{`);
  sourceLines.push(`\tSuper::PreAttributeChange(Attribute, NewValue);`);
  sourceLines.push(``);

  attributes.forEach((attr) => {
    sourceLines.push(`\tif (Attribute == Get${attr.name}Attribute())`);
    sourceLines.push(`\t{`);
    sourceLines.push(`\t\tNewValue = FMath::Clamp(NewValue, ${formatCppFloat(attr.minValue)}, ${formatCppFloat(attr.maxValue)});`);
    sourceLines.push(`\t}`);
  });

  sourceLines.push(`}`);
  sourceLines.push(``);

  // PostGameplayEffectExecute
  sourceLines.push(`void ${cleanClassName}::PostGameplayEffectExecute(const FGameplayEffectModCallbackData& Data)`);
  sourceLines.push(`{`);
  sourceLines.push(`\tSuper::PostGameplayEffectExecute(Data);`);
  sourceLines.push(``);
  sourceLines.push(`\tFGameplayEffectContextHandle Context = Data.EffectSpec.GetContext();`);
  sourceLines.push(`\tAActor* TargetActor = Data.Target.AbilityActorInfo->AvatarActor.Get();`);
  sourceLines.push(``);

  attributes.forEach((attr) => {
    sourceLines.push(`\tif (Data.EvaluatedData.Attribute == Get${attr.name}Attribute())`);
    sourceLines.push(`\t{`);
    sourceLines.push(`\t\tSet${attr.name}(FMath::Clamp(Get${attr.name}(), ${formatCppFloat(attr.minValue)}, ${formatCppFloat(attr.maxValue)}));`);
    sourceLines.push(`\t}`);
  });

  sourceLines.push(`}`);
  sourceLines.push(``);

  // GetLifetimeReplicatedProps
  sourceLines.push(`void ${cleanClassName}::GetLifetimeReplicatedProps(TArray<FLifetimeProperty>& OutLifetimeProps) const`);
  sourceLines.push(`{`);
  sourceLines.push(`\tSuper::GetLifetimeReplicatedProps(OutLifetimeProps);`);
  sourceLines.push(``);

  attributes.forEach((attr) => {
    if (attr.isReplicated) {
      sourceLines.push(`\tDOREPLIFETIME_CONDITION_NOTIFY(${cleanClassName}, ${attr.name}, COND_None, REPNOTIFY_Always);`);
    }
  });

  sourceLines.push(`}`);
  sourceLines.push(``);

  // OnRep functions
  attributes.forEach((attr) => {
    sourceLines.push(`void ${cleanClassName}::OnRep_${attr.name}(const FGameplayAttributeData& Old${attr.name})`);
    sourceLines.push(`{`);
    sourceLines.push(`\tGAMEPLAYATTRIBUTE_REPNOTIFY(${cleanClassName}, ${attr.name}, Old${attr.name});`);
    sourceLines.push(`}`);
    sourceLines.push(``);
  });

  return {
    headerFile: headerLines.join('\n'),
    sourceFile: sourceLines.join('\n'),
    className: cleanClassName,
  };
}

/**
 * Generates Unreal Engine 5 production-ready C++ GameplayAbility scaffolding (.h and .cpp)
 */
export function generateGameplayAbilityCpp(ability: GameplayAbilityDefinition): GasCppOutput {
  const cleanClassName = ability.abilityName.startsWith('U') ? ability.abilityName : `U${ability.abilityName}`;
  const rawName = cleanClassName.substring(1);

  const headerLines: string[] = [
    `// Generated by Noder GAS Studio — Unreal Engine 5 C++ Scaffolding`,
    `#pragma once`,
    ``,
    `#include "CoreMinimal.h"`,
    `#include "Abilities/GameplayAbility.h"`,
    `#include "${rawName}.generated.h"`,
    ``,
    `UCLASS()`,
    `class YOURGAME_API ${cleanClassName} : public UGameplayAbility`,
    `{`,
    `\tGENERATED_BODY()`,
    ``,
    `public:`,
    `\t${cleanClassName}();`,
    ``,
    `\tvirtual void ActivateAbility(const FGameplayAbilitySpecHandle Handle, const FGameplayAbilityActorInfo* ActorInfo, const FGameplayAbilityActivationInfo ActivationInfo, const FGameplayEventData* TriggerEventData) override;`,
    `\tvirtual void EndAbility(const FGameplayAbilitySpecHandle Handle, const FGameplayAbilityActorInfo* ActorInfo, const FGameplayAbilityActivationInfo ActivationInfo, bool bReplicateEndAbility, bool bWasCancelled) override;`,
    `};`,
  ];

  const sourceLines: string[] = [
    `// Generated by Noder GAS Studio — Unreal Engine 5 C++ Scaffolding`,
    `#include "${rawName}.h"`,
    `#include "AbilitySystemComponent.h"`,
    ``,
    `${cleanClassName}::${cleanClassName}()`,
    `{`,
    `\tInstancingPolicy = EGameplayAbilityInstancingPolicy::${ability.instancingPolicy};`,
    `\tNetExecutionPolicy = EGameplayAbilityNetExecutionPolicy::${ability.netExecutionPolicy};`,
    ``,
  ];

  // Configure Cost and Cooldown Effects if provided
  if (ability.costEffect) {
    const costClass = ability.costEffect.effectName.startsWith('U') 
      ? ability.costEffect.effectName 
      : `U${ability.costEffect.effectName}`;
    sourceLines.push(`\tCostGameplayEffectClass = ${costClass}::StaticClass();`);
  }
  if (ability.cooldownEffect) {
    const cdClass = ability.cooldownEffect.effectName.startsWith('U') 
      ? ability.cooldownEffect.effectName 
      : `U${ability.cooldownEffect.effectName}`;
    sourceLines.push(`\tCooldownGameplayEffectClass = ${cdClass}::StaticClass();`);
  }

  // Configure Tag Containers
  ability.tagPolicy.activationRequiredTags.forEach((tag) => {
    sourceLines.push(`\tActivationRequiredTags.AddTag(FGameplayTag::RequestGameplayTag(FName("${tag}")));`);
  });
  ability.tagPolicy.activationBlockedTags.forEach((tag) => {
    sourceLines.push(`\tActivationBlockedTags.AddTag(FGameplayTag::RequestGameplayTag(FName("${tag}")));`);
  });
  ability.tagPolicy.sourceGrantedTags.forEach((tag) => {
    sourceLines.push(`\tSourceGrantedTags.AddTag(FGameplayTag::RequestGameplayTag(FName("${tag}")));`);
  });
  if (ability.tagPolicy.targetTags && ability.tagPolicy.targetTags.length > 0) {
    ability.tagPolicy.targetTags.forEach((tag) => {
      sourceLines.push(`\tTargetRequiredTags.AddTag(FGameplayTag::RequestGameplayTag(FName("${tag}")));`);
    });
  }

  sourceLines.push(`}`);
  sourceLines.push(``);

  sourceLines.push(`void ${cleanClassName}::ActivateAbility(const FGameplayAbilitySpecHandle Handle, const FGameplayAbilityActorInfo* ActorInfo, const FGameplayAbilityActivationInfo ActivationInfo, const FGameplayEventData* TriggerEventData)`);
  sourceLines.push(`{`);
  sourceLines.push(`\tif (!CommitAbility(Handle, ActorInfo, ActivationInfo))`);
  sourceLines.push(`\t{`);
  sourceLines.push(`\t\tEndAbility(Handle, ActorInfo, ActivationInfo, true, true);`);
  sourceLines.push(`\t\treturn;`);
  sourceLines.push(`\t}`);
  sourceLines.push(``);
  sourceLines.push(`\t// Ability execution logic...`);
  sourceLines.push(`}`);
  sourceLines.push(``);

  sourceLines.push(`void ${cleanClassName}::EndAbility(const FGameplayAbilitySpecHandle Handle, const FGameplayAbilityActorInfo* ActorInfo, const FGameplayAbilityActivationInfo ActivationInfo, bool bReplicateEndAbility, bool bWasCancelled)`);
  sourceLines.push(`{`);
  sourceLines.push(`\tSuper::EndAbility(Handle, ActorInfo, ActivationInfo, bReplicateEndAbility, bWasCancelled);`);
  sourceLines.push(`}`);

  return {
    headerFile: headerLines.join('\n'),
    sourceFile: sourceLines.join('\n'),
    className: cleanClassName,
  };
}

/**
 * Generates Unreal Engine 5 production-ready C++ GameplayEffect scaffolding (.h and .cpp)
 * with duration policy, attribute modifiers, and granted tags.
 */
export function generateGameplayEffectCpp(effect: GameplayEffectDefinition): GasCppOutput {
  const cleanClassName = effect.effectName.startsWith('U') ? effect.effectName : `U${effect.effectName}`;
  const rawName = cleanClassName.substring(1);

  const headerLines: string[] = [
    `// Generated by Noder GAS Studio — Unreal Engine 5 C++ Scaffolding`,
    `#pragma once`,
    ``,
    `#include "CoreMinimal.h"`,
    `#include "GameplayEffect.h"`,
    `#include "${rawName}.generated.h"`,
    ``,
    `UCLASS()`,
    `class YOURGAME_API ${cleanClassName} : public UGameplayEffect`,
    `{`,
    `\tGENERATED_BODY()`,
    ``,
    `public:`,
    `\t${cleanClassName}();`,
    `};`,
  ];

  const sourceLines: string[] = [
    `// Generated by Noder GAS Studio — Unreal Engine 5 C++ Scaffolding`,
    `#include "${rawName}.h"`,
    `#include "BaseAttributeSet.h"`,
    ``,
    `${cleanClassName}::${cleanClassName}()`,
    `{`,
    `\tDurationPolicy = EGameplayEffectDurationType::${effect.durationPolicy};`,
  ];

  if (effect.durationPolicy === 'HasDuration') {
    sourceLines.push(`\tDurationMagnitude = FGameplayEffectModifierMagnitude(FScalableFloat(${formatCppFloat(effect.durationMagnitude)}));`);
  }

  if (effect.modifiers && effect.modifiers.length > 0) {
    sourceLines.push(``);
    sourceLines.push(`\t// Configure Attribute Modifiers`);
    effect.modifiers.forEach((mod) => {
      sourceLines.push(`\t{`);
      sourceLines.push(`\t\tFGameplayModifierInfo ModInfo;`);
      sourceLines.push(`\t\tModInfo.Attribute = FGameplayAttribute(UBaseAttributeSet::Get${mod.attribute}Attribute());`);
      sourceLines.push(`\t\tModInfo.ModifierOp = EGameplayModOp::${mod.modifierOp};`);
      sourceLines.push(`\t\tModInfo.ModifierMagnitude = FGameplayEffectModifierMagnitude(FScalableFloat(${formatCppFloat(mod.magnitude)}));`);
      sourceLines.push(`\t\tModifiers.Add(ModInfo);`);
      sourceLines.push(`\t}`);
    });
  }

  if (effect.grantedTags && effect.grantedTags.length > 0) {
    sourceLines.push(``);
    sourceLines.push(`\t// Configure Granted Tags`);
    effect.grantedTags.forEach((tag) => {
      sourceLines.push(`\tInheritableGameplayEffectTags.Added.AddTag(FGameplayTag::RequestGameplayTag(FName("${tag}")));`);
    });
  }

  sourceLines.push(`}`);

  return {
    headerFile: headerLines.join('\n'),
    sourceFile: sourceLines.join('\n'),
    className: cleanClassName,
  };
}

